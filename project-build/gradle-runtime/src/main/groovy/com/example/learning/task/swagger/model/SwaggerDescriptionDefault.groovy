package com.example.learning.task.swagger.model

class SwaggerDescriptionDefault {

    final String summary

    final String description

    final String videoYoutubeId


    SwaggerDescriptionDefault(
            String summary,
            String description,
            String videoYoutubeId
    ) {

        this.summary =
                summary

        this.description =
                description

        this.videoYoutubeId =
                videoYoutubeId
    }
}